"""Структурована відповідь GM за один хід гравця.

GMAnswer - те, що заповнює модель (розповідь і впевненість). GMResponse - те, що
зберігає граф: до GMAnswer додається список інструментів, які справді викликались.
Список заповнює код, а не модель, тож він не може бути вигаданим.
"""

from pydantic import BaseModel, Field


class GMAnswer(BaseModel):
    """Відповідь, яку модель заповнює у форматері."""

    answer: str = Field(
        min_length=1,
        description="Розповідь для гравця українською: що сталося і що бачить персонаж.",
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Впевненість від 0 до 1: 1 - усі факти підтверджені інструментами, менше - є здогади.",
    )


class GMResponse(GMAnswer):
    """Відповідь за хід, яку зберігає граф."""

    sources: list[str] = Field(
        default_factory=list,
        description="Назви інструментів, викликаних у цьому ходу. Заповнює код.",
    )
