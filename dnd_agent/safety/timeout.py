"""Таймаути: межа часу на один хід гравця і на один запит до моделі.

Дедлайн ходу ставиться в стані на першому виклику моделі в ході і перевіряється
перед кожним наступним викликом і перед подією світу. Запит до моделі обмежує сам клієнт.
"""

import time

# Скільки секунд може тривати один хід гравця (від першого виклику моделі)
TURN_TIMEOUT_SECONDS = 90.0
# Скільки секунд чекаємо відповідь від моделі на один запит
MODEL_REQUEST_TIMEOUT_SECONDS = 30.0

# Ім'я системного повідомлення, яким позначається зупинка через час
TIMEOUT = "timeout"
TIMEOUT_MESSAGE = (
    "Час ходу вичерпано: хід зупинено. Коротко опиши, що встиг зробити персонаж, "
    "і чекай наступної дії гравця."
)


def deadline_passed(deadline: float | None) -> bool:
    """Чи минув дедлайн. Без дедлайну (None) час не обмежений."""
    return deadline is not None and time.monotonic() >= deadline
